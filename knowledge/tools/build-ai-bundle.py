#!/usr/bin/env python3
"""build-ai-bundle.py — generate manifest.json and ai-bundle.md.

Usage: python3 build-ai-bundle.py [repo-root]

For AI tools (ChatGPT, Claude, any agent) that download this repo and
use it locally:

  * manifest.json — machine-readable map: purpose, reading order, and
    every content file with a one-line summary and size.
  * ai-bundle.md — the whole knowledge base concatenated into ONE
    markdown file, in reading order, so it can be uploaded or pasted
    as a single document. The bundle contains docs and reference
    material; code files (templates, tools, examples' configs) are
    listed in the manifest instead of inlined.

Reading order: README.md, AGENTS.md, SOURCES.md (if present), docs/
in filename order, reference/, checklists/, then the folder READMEs
of templates/, examples/, tools/. Regenerate after any content
change; both outputs are stamped with the generation date.
Python 3, standard library only.
"""

import json
import os
import sys
from datetime import date

SKIP_DIRS = {".git", "__pycache__"}
BUNDLE_EXTS = {".md"}
ROOT_ORDER = ["README.md", "AGENTS.md", "SOURCES.md"]
DIR_ORDER = ["docs", "reference", "checklists"]


def first_heading(path):
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            for line in fh:
                line = line.strip()
                if line.startswith("#"):
                    return line.lstrip("# ").strip()
                if line:
                    return line[:100]
    except OSError:
        pass
    return ""


def collect(root):
    files = []
    for dirpath, dirs, names in os.walk(root):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        for n in names:
            p = os.path.relpath(os.path.join(dirpath, n), root)
            files.append(p.replace(os.sep, "/"))
    return sorted(files)


def reading_order(files):
    ordered = []
    for name in ROOT_ORDER:
        if name in files:
            ordered.append(name)
    for d in DIR_ORDER:
        ordered += [f for f in files if f.startswith(d + "/")]
    for d in ("templates", "examples", "tools"):
        ordered += [f for f in files if f == d + "/README.md"]
    return ordered


def main() -> int:
    root = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else ".")
    repo = os.path.basename(root)
    files = collect(root)
    order = reading_order(files)

    manifest = {
        "repo": repo,
        "generated": date.today().isoformat(),
        "purpose": first_heading(os.path.join(root, "README.md")),
        "startHere": ["AGENTS.md", "README.md"],
        "readingOrder": order,
        "files": [
            {
                "path": f,
                "bytes": os.path.getsize(os.path.join(root, f)),
                "summary": first_heading(os.path.join(root, f))
                if f.endswith(".md") else "",
            }
            for f in files
            if f not in ("manifest.json", "ai-bundle.md")
        ],
    }
    with open(os.path.join(root, "manifest.json"), "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=2)

    bundle_path = os.path.join(root, "ai-bundle.md")
    with open(bundle_path, "w", encoding="utf-8") as out:
        out.write(f"# {repo} — AI bundle\n\n")
        out.write(
            "The complete knowledge base in one file, generated by "
            f"tools/build-ai-bundle.py on {date.today().isoformat()}. "
            "Generated file — edit the sources, not this bundle. "
            "Code files (templates, tools, example configs) are not "
            "inlined; see manifest.json for the full file map. "
            "Relative links inside the bundle point at the original "
            "files in the repo — open the source file (named in the "
            "section markers) for working links.\n\n"
        )
        for rel in order:
            path = os.path.join(root, rel)
            if not rel.endswith(".md") or not os.path.exists(path):
                continue
            out.write(f"\n\n---\n\n<!-- ===== {rel} ===== -->\n\n")
            with open(path, encoding="utf-8", errors="replace") as fh:
                out.write(fh.read())
    print(f"manifest.json: {len(manifest['files'])} files")
    print(f"ai-bundle.md: {os.path.getsize(bundle_path)} bytes, "
          f"{len(order)} documents in reading order")
    return 0


if __name__ == "__main__":
    sys.exit(main())
