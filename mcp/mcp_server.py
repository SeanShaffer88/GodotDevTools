#!/usr/bin/env python3
"""GodotDevTools MCP server (stdio, stdlib only, offline).

Exposes each tool CLI as an MCP tool so AI agents (Claude, Cursor) can run
checks without shelling out manually. Tools are discovered from
docs/catalog.json (generated by tools/docs_site/generate.py).

Protocol: newline-delimited JSON-RPC 2.0 over stdio (MCP-compatible subset).
Run: python3 mcp/mcp_server.py  (needs a Godot binary in PATH or GODOT_BIN)
"""
import json, os, subprocess, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
CATALOG = ROOT / "docs" / "catalog.json"

def load_catalog():
    if CATALOG.exists():
        return json.loads(CATALOG.read_text()).get("tools", [])
    return []

def godot_bin():
    return os.environ.get("GODOT_BIN", "godot")

def handle(method, params):
    if method == "initialize":
        return {"protocolVersion": "2024-11-05", "capabilities": {"tools": {}}, "serverInfo": {"name": "godot-dev-tools", "version": "1.0.0"}}
    if method == "tools/list":
        tools = [{"name": "list_tools", "description": "List all GodotDevTools tools from the catalog.", "inputSchema": {"type": "object", "properties": {}}}]
        for t in load_catalog():
            if t.get("cli"):
                tools.append({"name": f"run_{t['id']}", "description": f"Run {t['title']}: {t['description']}", "inputSchema": {"type": "object", "properties": {"args": {"type": "array", "items": {"type": "string"}, "description": "Extra CLI args, e.g. ['--fail-on=errors']"}}}})
        tools.append({"name": "search_tools", "description": "Search tools by problem phrase (delegates to tool_finder logic via catalog keywords).", "inputSchema": {"type": "object", "properties": {"query": {"type": "string"}}, "required": ["query"]}})
        return {"tools": tools}
    if method == "tools/call":
        name = params.get("name", "")
        args = (params.get("arguments") or {}).get("args", [])
        if name == "list_tools":
            return {"content": [{"type": "text", "text": json.dumps(load_catalog(), indent=2)}]}
        if name == "search_tools":
            q = (params.get("arguments") or {}).get("query", "").lower()
            hits = [t for t in load_catalog() if q in (t["title"] + " " + t["description"] + " " + t["id"]).lower()]
            return {"content": [{"type": "text", "text": json.dumps(hits, indent=2)}]}
        if name.startswith("run_"):
            tool_id = name[4:]
            tool = next((t for t in load_catalog() if t["id"] == tool_id), None)
            if not tool or not tool.get("cli"):
                return {"content": [{"type": "text", "text": f"unknown tool: {tool_id}"}], "isError": True}
            cli = "res://" + tool["cli"]
            cmd = [godot_bin(), "--headless", "--path", str(ROOT), "--script", cli, "--"] + [str(a) for a in args]
            proc = subprocess.run(cmd, capture_output=True, text=True, timeout=300)
            return {"content": [{"type": "text", "text": f"exit={proc.returncode}\n{proc.stdout}\n{proc.stderr}"}], "isError": proc.returncode not in (0, 2)}
        return {"content": [{"type": "text", "text": f"unknown tool: {name}"}], "isError": True}
    if method == "ping":
        return {}
    raise ValueError(f"unsupported method: {method}")

def main():
    for line in sys.stdin:
        line = line.strip()
        if not line:
            continue
        try:
            req = json.loads(line)
            result = handle(req.get("method", ""), req.get("params") or {})
            resp = {"jsonrpc": "2.0", "id": req.get("id"), "result": result}
        except Exception as e:
            resp = {"jsonrpc": "2.0", "id": None, "error": {"code": -32603, "message": str(e)}}
        print(json.dumps(resp), flush=True)

if __name__ == "__main__":
    main()
