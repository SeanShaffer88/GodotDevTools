#!/usr/bin/env python3
"""Generate Godot Asset Library submission metadata from addons/*/plugin.cfg.
Usage: python3 tools/assetlib/generate_assetlib.py [--out=assetlib]
Writes assetlib/<tool>.json per tool + assetlib/README.md checklist.
Stdlib only. See docs/ASSETLIB.md.
"""
import json, pathlib, sys
ROOT = pathlib.Path(__file__).resolve().parents[2]
def parse_cfg(p):
    d = {}
    for line in p.read_text(errors="ignore").splitlines():
        if "=" in line and line.split("=",1)[0].strip() in ("name","description","version","author"):
            k, v = line.split("=", 1)
            d[k.strip()] = v.strip().strip('"')
    return d
def main():
    out = ROOT / "assetlib"
    out.mkdir(exist_ok=True)
    count = 0
    for folder in sorted((ROOT / "addons").iterdir()):
        cfg = folder / "plugin.cfg"
        if not cfg.exists():
            continue
        meta = parse_cfg(cfg)
        entry = {"asset_name": meta.get("name", folder.name), "folder": folder.name,
                 "version": meta.get("version", "1.0.0"), "author": meta.get("author", "Sean Shaffer"),
                 "description": meta.get("description", ""), "category": "Tools",
                 "godot_version": "4.3", "license": "MIT",
                 "zip": f"GodotDevTools-{folder.name}-{meta.get('version','1.0.0')}.zip",
                 "readme": f"addons/{folder.name}/README.md"}
        (out / f"{folder.name}.json").write_text(json.dumps(entry, indent=2) + "\n")
        count += 1
    (out / "README.md").write_text(f"# Asset Library submissions\n\n{count} per-tool entries generated by `tools/assetlib/generate_assetlib.py`.\n\n## Checklist per tool\n\n1. Build the zip: `zip -qrD GodotDevTools-<tool>-<version>.zip addons/<tool>` (release.yml does this on tags).\n2. Submit at https://godotengine.org/asset-library/ with the matching `<tool>.json` fields.\n3. Link the Asset Library page from the tool README.\n\nSee docs/ASSETLIB.md.\n")
    print(f"assetlib: {count} entries -> assetlib/")
if __name__ == "__main__":
    main()
