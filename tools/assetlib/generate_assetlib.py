#!/usr/bin/env python3
"""Generate Godot Asset Library submission metadata from addon plugin.cfg files."""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools" / "release"))
from release_manifest import ManifestError, archive_name, load_manifest, validate_tag


def parse_cfg(path):
    values = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if "=" in line and line.split("=", 1)[0].strip() in ("name", "description", "version", "author"):
            key, value = line.split("=", 1)
            values[key.strip()] = value.strip().strip('"')
    return values


def render(root, release_tag=None):
    manifest = load_manifest(root)
    if release_tag is not None:
        validate_tag(release_tag)
    outputs = {}
    for folder, stem in manifest.items():
        meta = parse_cfg(Path(root) / "addons" / folder / "plugin.cfg")
        version = meta.get("version", "1.0.0")
        # Preserve the existing untagged metadata format. Release names use a
        # tag, which is not necessarily the same as the plugin's version.
        zip_name = archive_name(stem, release_tag) if release_tag else f"GodotDevTools-{folder}-{version}.zip"
        entry = {"asset_name": meta.get("name", folder), "folder": folder,
                 "version": version, "author": meta.get("author", "Sean Shaffer"),
                 "description": meta.get("description", ""), "category": "Tools",
                 "godot_version": "4.3", "license": "MIT", "zip": zip_name,
                 "readme": f"addons/{folder}/README.md"}
        outputs[f"{folder}.json"] = json.dumps(entry, indent=2) + "\n"

    if release_tag:
        context = f"Archive names target `{release_tag}`; the plugin versions still come from each `plugin.cfg`."
    else:
        context = ("The checked-in `zip` fields use legacy local names, not GitHub Release names. "
                   "Generate tagged metadata as described below when preparing a release.")
    outputs["README.md"] = (
        "# Asset Library submissions\n\n"
        f"{len(manifest)} per-tool entries generated by `tools/assetlib/generate_assetlib.py`.\n\n"
        f"{context}\n\n"
        "## Checklist per tool\n\n"
        "1. Generate metadata with `--release-tag v1.2.3 --out <directory>`, using the actual release tag. "
        "The tag and plugin version need not match.\n"
        "2. Build the matching archives or verify they exist on the intended GitHub Release; "
        "generation does not check whether a release or asset exists.\n"
        "3. Submit at https://godotengine.org/asset-library/ with the matching JSON fields and actual archive URL.\n"
        "4. Link the Asset Library page from the tool README.\n\n"
        "See docs/ASSETLIB.md.\n"
    )
    return outputs


def check_outputs(out, outputs):
    problems = []
    for name, expected in outputs.items():
        path = out / name
        if not path.is_file():
            problems.append(f"missing: {path}")
        elif path.read_text(encoding="utf-8") != expected:
            problems.append(f"out of date: {path}")
    if out.is_dir():
        for path in sorted(out.glob("*.json")):
            if path.name not in outputs:
                problems.append(f"unexpected metadata: {path}")
    return problems


def write_outputs(root, out, outputs):
    out = out.absolute()
    if out.is_symlink():
        raise ManifestError(f"output directory cannot be a symlink: {out}")
    out = out.resolve()
    addons = (Path(root) / "addons").resolve()
    if out == Path(root).resolve() or out == addons or addons in out.parents:
        raise ManifestError("metadata output cannot be the repository root or inside addons/")
    if out.exists():
        if not out.is_dir():
            raise ManifestError(f"metadata output is not a directory: {out}")
        if any(out.iterdir()):
            readme = out / "README.md"
            marker = "per-tool entries generated by `tools/assetlib/generate_assetlib.py`"
            if readme.is_symlink() or not readme.is_file() or marker not in readme.read_text(encoding="utf-8"):
                raise ManifestError(f"metadata output must be empty or previously generated: {out}")
        for name in outputs:
            path = out / name
            if path.is_symlink() or (path.exists() and not path.is_file()):
                raise ManifestError(f"refusing to overwrite non-regular metadata file: {path}")
    out.mkdir(parents=True, exist_ok=True)
    for name, content in outputs.items():
        (out / name).write_text(content, encoding="utf-8")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=ROOT / "assetlib", help="output directory (default: repository assetlib/)")
    parser.add_argument("--release-tag", help="use release asset names for this vMAJOR.MINOR.PATCH tag")
    parser.add_argument("--check", action="store_true", help="report stale or missing generated metadata without writing")
    args = parser.parse_args(argv)
    try:
        outputs = render(ROOT, args.release_tag)
        if args.check:
            problems = check_outputs(args.out, outputs)
            if problems:
                print("\n".join(problems), file=sys.stderr)
                return 1
        else:
            write_outputs(ROOT, args.out, outputs)
    except (ManifestError, OSError, UnicodeError) as exc:
        print(f"assetlib: {exc}", file=sys.stderr)
        return 1
    print(f"assetlib: {len(outputs) - 1} entries {'checked in' if args.check else 'written to'} {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
