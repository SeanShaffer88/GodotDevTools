#!/usr/bin/env python3
"""Generate docs/catalog.json + docs/TOOLS.md from addons/*/plugin.cfg + README.
Usage: python3 tools/docs_site/generate.py
Stdlib only. Run in CI (docs workflow) or locally before committing docs changes.
"""
import json, pathlib, re
ROOT = pathlib.Path(__file__).resolve().parents[2]
ADDONS = ROOT / "addons"
def parse_cfg(p):
    d = {}
    for line in p.read_text(errors="ignore").splitlines():
        if "=" in line and line.split("=",1)[0].strip() in ("name","description","version"):
            k, v = line.split("=", 1)
            d[k.strip()] = v.strip().strip('"')
    return d
def main():
    catalog = []
    for folder in sorted(ADDONS.iterdir()):
        cfg = folder / "plugin.cfg"
        if not cfg.exists():
            continue
        meta = parse_cfg(cfg)
        readme = folder / "README.md"
        first = ""
        if readme.exists():
            for line in readme.read_text(errors="ignore").splitlines():
                if line.strip() and not line.startswith("#"):
                    first = line.strip()[:200]
                    break
        cli = sorted((folder / "cli").glob("*_cli.gd")) if (folder / "cli").exists() else []
        catalog.append({"id": folder.name, "title": meta.get("name", folder.name),
                        "description": meta.get("description", ""), "version": meta.get("version", ""),
                        "folder": f"addons/{folder.name}", "readme": f"addons/{folder.name}/README.md",
                        "cli": f"addons/{folder.name}/cli/{cli[0].name}" if cli else "",
                        "summary": first})
    (ROOT / "docs" / "catalog.json").write_text(json.dumps({"count": len(catalog), "tools": catalog}, indent=2) + "\n")
    lines = ["# Tool catalog", "", f"{len(catalog)} tools. Generated by `tools/docs_site/generate.py` — do not edit by hand.", "", "| Tool | What it does | Folder | CLI |", "|---|---|---|---|"]
    for t in catalog:
        lines.append(f"| [{t['title']}]({t['readme']}) | {t['description']} | `{t['folder']}` | `{t['cli']}` |")
    (ROOT / "docs" / "TOOLS.md").write_text("\n".join(lines) + "\n")
    print(f"catalog: {len(catalog)} tools -> docs/catalog.json, docs/TOOLS.md")
if __name__ == "__main__":
    main()
